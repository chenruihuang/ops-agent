# =====================================================================
# 容量基线表：从服务手册派生，而不是手写第二份
# =====================================================================
# 为什么必须派生
# --------------
# 副本数已经在服务手册（`svc-*` 文档的"基本信息"表）里定义过了。
# 容量规划里再手写一份，**必然**会出现「手册说 4 副本、容量表说 6 副本」
# 这类矛盾 —— 而且它不会报错：检索时会把两个互相冲突的答案一起返回，
# 直接损害生成层的忠实度，而排查时又要花时间判断"哪个才是对的"。
# 实测第一版手写表格就产生了 9 处不一致。
#
# 派生之后还有第二个好处：余量列是**算出来**的，不是抄出来的。
# 手算余量会引入算术错误，而表格里的数字若不自洽，任何一句
# "余量为负的服务有几个"的结论都会随之失真。
#
# 下表只保留真正属于"容量视角"的增量数据：单副本吞吐、当前峰值、预测峰值。
_CAPACITY_PROFILE: dict[str, tuple[int, int, int]] = {
    # 服务 key : (单副本 QPS, 当前峰值 QPS, 预测峰值 QPS)
    # 单副本 QPS = 压测实测 × 0.7 回退系数（见"规划方法与口径"）
    "gateway": (1800, 7200, 10400),
    "order-service": (620, 4100, 5900),
    "payment-gateway": (480, 1700, 2500),
    "user-center": (900, 3800, 4900),
    "inventory-service": (750, 2600, 3400),
    "search-service": (400, 2100, 3150),
    "notify-service": (300, 800, 1150),
    "promotion-service": (520, 1900, 2700),
    "risk-engine": (410, 1100, 1500),
    "ops-agent": (350, 950, 1300),
    "report-job": (120, 190, 240),
    "file-service": (280, 700, 900),
}

SAFETY_FACTOR = 1.3
MINUS = "\u2212"


def _capacity_table() -> str:
    svc_by_key = {str(s["key"]): s for s in SERVICES}
    header = ["服务", "副本数", "单副本 QPS", "峰值 QPS", "预测峰值", "余量"]
    lines = [
        "| " + " | ".join(header) + " |",
        "|" + "|".join([" --- "] * len(header)) + "|",
    ]
    for key, (unit_qps, peak, forecast) in _CAPACITY_PROFILE.items():
        replicas = int(svc_by_key[key]["replicas"])
        headroom = replicas * unit_qps / (forecast * SAFETY_FACTOR) - 1
        sign = "+" if headroom >= 0 else MINUS
        lines.append(
            f"| `svc-{key}` | {replicas} | {unit_qps} | {peak} | {forecast} "
            f"| {sign}{abs(headroom) * 100:.0f}% |"
        )
    return "\n".join(lines)


def _negative_headroom_count() -> int:
    svc_by_key = {str(s["key"]): s for s in SERVICES}
    return sum(
        1
        for key, (unit_qps, _peak, forecast) in _CAPACITY_PROFILE.items()
        if int(svc_by_key[key]["replicas"]) * unit_qps / (forecast * SAFETY_FACTOR) - 1 < 0
    )


CAPACITY_TABLE = _capacity_table()
NEGATIVE_HEADROOM = _negative_headroom_count()

